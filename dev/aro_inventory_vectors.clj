;; Writes test/briko/inventory_vectors.edn with aro's own code: records
;; from synthetic forge JSON through aro.forge's record functions, text
;; through aro.inventory/write-inventory! in a temporary directory, and
;; what aro.inventory/parse reads back. Run it from the briko checkout
;; against the src directory of an aro checkout:
;;
;;   bb -cp <aro>/src dev/aro_inventory_vectors.clj > test/briko/inventory_vectors.edn
(require '[aro.forge :as forge] '[aro.inventory :as inv] '[cheshire.core :as json] '[babashka.fs :as fs] '[clojure.pprint :as pp])
(def gh #'forge/github-record)
(def gl #'forge/gitlab-record)
(defn ghj [host m] (gh host (json/parse-string (json/generate-string m) true)))
(defn glj [host m] (gl host (json/parse-string (json/generate-string m) true)))
(def many-props (into {} (for [i (range 12)] [(str "p" i) (str "v" i)])))
(def cases
  [{:name "empty" :inventory {:header "" :sources {}}}
   {:name "empty-source" :inventory {:header "" :sources {"metio" []}}}
   {:name "github-org"
    :inventory {:header ""
                :sources {"metio" [(ghj "github.com" {:name "zeta" :full_name "metio/zeta" :default_branch "main" :archived false :fork false :topics ["b" "a"]})
                                   (ghj "github.com" {:name "aro" :full_name "metio/aro" :default_branch "main" :archived true :fork true :topics []
                                                      :custom_properties {:release "maven-central" :features ["docs" "website"] :gone nil}})
                                   (ghj "github.com" {:name "many" :full_name "metio/many" :default_branch "trunk" :archived false :fork false :topics nil
                                                      :custom_properties many-props})]}}}
   {:name "gitlab-and-github-unsorted"
    :inventory {:header ""
                :sources {"work" [(glj "gitlab.example.org" {:path "proj" :path_with_namespace "group/sub/proj" :namespace {:full_path "group/sub"} :default_branch nil :archived false :topics ["x"] :forked_from_project {:id 1}})
                                  (glj "gitlab.example.org" {:path "Äpfel" :path_with_namespace "group/Äpfel" :namespace {:full_path "group"} :default_branch "master" :archived false :topics ["ü \"quoted\""]})]
                          "me" [(ghj "github.com" {:name "dotfiles" :full_name "me/dotfiles" :default_branch "main" :archived false :fork false :topics ["config"]})]
                          "a-first" [(ghj "github.com" {:name "x" :full_name "a/x" :default_branch "main" :archived false :fork false :topics []})]}}}
   {:name "header"
    :inventory {:header ";; Copyright somebody else\n;; under their own terms\n\n  ; indented comment"
                :sources {"me" [(ghj "github.com" {:name "dotfiles" :full_name "me/dotfiles" :default_branch "main" :archived false :fork false :topics []})]}}}
   {:name "same-repo-in-two-sources"
    :inventory {:header ""
                :sources {"org" [(ghj "github.com" {:name "aro" :full_name "metio/aro" :default_branch "main" :archived false :fork false :topics []})]
                          "mine" [(ghj "github.com" {:name "aro" :full_name "metio/aro" :default_branch "main" :archived false :fork false :topics []})]}}}])
(def root (str (fs/create-temp-dir {:prefix "aro-golden-"})))
(def out
  (vec (for [{:keys [name inventory]} cases]
         (let [file (str root "/" name "/inventory.edn")
               _ (inv/write-inventory! file inventory)
               text (slurp file)]
           (assert (= text (inv/render inventory)))
           (assert (= text (inv/render (inv/parse text))))
           {:name name :inventory inventory :text text :parsed (inv/parse text)}))))
(fs/delete-tree root)
(binding [*print-namespace-maps* false]
  ;; REUSE-IgnoreStart
  (println ";; SPDX-FileCopyrightText: The briko Authors")
  (println ";; SPDX-License-Identifier: 0BSD")
  ;; REUSE-IgnoreEnd
  (println)
  (println ";; Inventories written by aro.inventory/write-inventory! of aro 2338c84,")
  (println ";; with records built by aro.forge from synthetic forge JSON, and what")
  (println ";; aro.inventory/parse reads back from each text. Generated by")
  (println ";; dev/aro_inventory_vectors.clj; do not edit by hand.")
  (pp/pprint out))
